using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using UnityEditor;
using UnityEngine;
using UOClient.Content;

namespace UOClient.EditorTools
{
    /// <summary>
    /// Writes <c>ContentKey.Local.cs</c>: a random 256-bit content-pack key as 32 single-byte
    /// assignments in shuffled order, so IL2CPP compiles them into scattered native immediates
    /// instead of one array blob. The file is git-ignored; it never leaves this machine except
    /// compiled into a release player.
    /// </summary>
    public static class ContentKeyGenerator
    {
        public const string KeyFilePath = "Assets/UOClient/Scripts/Content/ContentKey.Local.cs";

        public static bool HasKey => ContentKey.Get() != null;

        [MenuItem("UO Client/Release/Generate Content Key")]
        public static void GenerateMenu()
        {
            if (File.Exists(KeyFilePath) &&
                !EditorUtility.DisplayDialog("Replace content key?",
                    "A content key already exists. Old release builds keep working (each ships its own pack), " +
                    "but the next release will use the new key.", "Replace", "Cancel"))
            {
                return;
            }

            Generate();
        }

        /// <summary>Writes a fresh key file and recompiles. Safe to call from the CLI.</summary>
        public static void Generate()
        {
            var key = new byte[ContentKey.Size];
            var order = new byte[ContentKey.Size];
            using (var rng = RandomNumberGenerator.Create())
            {
                rng.GetBytes(key);
                rng.GetBytes(order);
            }

            // Every byte non-zero keeps ContentKey.Get()'s "all zero means no key" check unambiguous.
            for (int i = 0; i < key.Length; i++)
            {
                if (key[i] == 0) key[i] = (byte)(i + 1);
            }

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated> Content-pack key for release builds. Generated by UO Client > Release >");
            sb.AppendLine("// Generate Content Key. NEVER COMMIT THIS FILE (it is git-ignored). </auto-generated>");
            sb.AppendLine("namespace UOClient.Content");
            sb.AppendLine("{");
            sb.AppendLine("    internal static partial class ContentKey");
            sb.AppendLine("    {");
            sb.AppendLine("        static partial void Fill(byte[] k)");
            sb.AppendLine("        {");
            foreach (int i in Enumerable.Range(0, key.Length).OrderBy(i => order[i]).ThenBy(i => i))
            {
                byte mask = (byte)(order[i] | 1);
                sb.AppendLine($"            k[{i}] = (byte)(0x{(byte)(key[i] ^ mask):X2} ^ 0x{mask:X2});");
            }

            sb.AppendLine("        }");
            sb.AppendLine("    }");
            sb.AppendLine("}");

            File.WriteAllText(KeyFilePath, sb.ToString());
            AssetDatabase.ImportAsset(KeyFilePath);
            Debug.Log($"[Release] Wrote a new content key to {KeyFilePath}. Scripts will recompile.");
        }
    }
}
