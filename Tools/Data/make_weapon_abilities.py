"""Generates Assets/UOClient/Scripts/Core/Data/WeaponAbilities.g.cs from the shard's ServUO scripts: for every
weapon item graphic, its primary and secondary special move (as WeaponAbility indexes). Classes inherit both from
their base class when they don't override them. Re-run after the server's weapons change:
    python -I make_weapon_abilities.py "G:/Ultima Online/ServUO/Scripts"
"""
import os, re, sys

root = sys.argv[1] if len(sys.argv) > 1 else "G:/Ultima Online/ServUO/Scripts"
NAMES = ["None", "ArmorIgnore", "BleedAttack", "ConcussionBlow", "CrushingBlow", "Disarm", "Dismount", "DoubleStrike",
         "InfectiousStrike", "MortalStrike", "MovingShot", "ParalyzingBlow", "ShadowStrike", "WhirlwindAttack",
         "RidingSwipe", "FrenziedWhirlwind", "Block", "DefenseMastery", "NerveStrike", "TalonStrike", "Feint",
         "DualWield", "DoubleShot", "ArmorPierce", "Bladeweave", "ForceArrow", "LightningArrow", "PsychicAttack",
         "SerpentArrow", "ForceOfNature", "InfusedThrow", "MysticArc", "Disrobe", "ColdWind"]
INDEX = {n: i for i, n in enumerate(NAMES)}

cls_re = re.compile(r"\bclass\s+(\w+)\s*:\s*([\w.]+)")
classes = {}  # name -> dict(base, graphic, primary, secondary)
for dirpath, _, files in os.walk(root):
    for f in files:
        if not f.endswith(".cs"):
            continue
        text = open(os.path.join(dirpath, f), encoding="utf-8", errors="replace").read()
        matches = list(cls_re.finditer(text))
        for i, m in enumerate(matches):
            body = text[m.end(): matches[i + 1].start() if i + 1 < len(matches) else len(text)]
            name, base = m.group(1), m.group(2).split(".")[-1]
            info = {"base": base, "graphic": None, "primary": None, "secondary": None}
            g = re.search(r"\[Constructable\][^{]*?\)\s*:\s*base\s*\(\s*(0x[0-9A-Fa-f]+)", body)
            if g:
                info["graphic"] = int(g.group(1), 16)
            for key, prop in (("primary", "PrimaryAbility"), ("secondary", "SecondaryAbility")):
                a = re.search(prop + r"\s*(?:\{\s*get\s*\{\s*return|=>)\s*WeaponAbility\.(\w+)", body)
                if a and a.group(1) in INDEX:
                    info[key] = a.group(1)
            classes.setdefault(name, info)

def resolve(name, key, depth=0):
    info = classes.get(name)
    if info is None or depth > 20:
        return None
    return info[key] if info[key] is not None else resolve(info["base"], key, depth + 1)

def is_weapon(name, depth=0):
    info = classes.get(name)
    if info is None or depth > 20:
        return False
    return name == "BaseWeapon" or is_weapon(info["base"], depth + 1)

table = {}
for name, info in classes.items():
    if info["graphic"] is None or not is_weapon(name):
        continue
    p, s = resolve(name, "primary"), resolve(name, "secondary")
    if p and s:
        table.setdefault(info["graphic"], (INDEX[p], INDEX[s], name))

out = "G:/Ultima Online/UnityClient/Assets/UOClient/Scripts/Core/Data/WeaponAbilities.g.cs"
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by Tools/Data/make_weapon_abilities.py from the shard's ServUO weapon scripts. Don't edit.\n")
    f.write("using System.Collections.Generic;\n\nnamespace UOClient.Data\n{\n    public static class WeaponAbilities\n    {\n")
    f.write("        public static readonly string[] Names =\n        {\n")
    readable = [re.sub(r"(?<!^)(?=[A-Z])", " ", n) for n in NAMES]
    f.write("            " + ", ".join('"%s"' % n for n in readable) + ",\n        };\n\n")
    f.write("        /// <summary>Weapon item graphic → (primary, secondary) ability index.</summary>\n")
    f.write("        public static readonly Dictionary<ushort, (byte Primary, byte Secondary)> ByGraphic = new Dictionary<ushort, (byte, byte)>\n        {\n")
    for g in sorted(table):
        p, s, n = table[g]
        f.write(f"            [0x{g:04X}] = ({p}, {s}), // {n}\n")
    f.write("        };\n\n")
    f.write("        /// <summary>Unarmed (wrestling).</summary>\n        public static readonly (byte Primary, byte Secondary) Fists = (5, 11);\n")
    f.write("    }\n}\n")
print(len(table), "weapons")
